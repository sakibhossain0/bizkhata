extension TX on T {
  String get s => currentLang == Lang.bn ? bn : en;

  String f(Map<String, Object?> args) {
    var out = s;
    args.forEach((k, v) => out = out.replaceAll('{$k}', '${v ?? ''}'));
    return out;
  }
}

