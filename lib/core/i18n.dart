/// Unit as shown to the user ("kg" → "কেজি" in Bangla). Stored values stay in English.
String unitLabel(String? unit) {
  if (unit == null || unit.isEmpty) return '';
  return isBangla ? (_unitBn[unit] ?? unit) : unit;
}

/// "1 item" / "3 items".
String itemsText(int n) => n == 1 ? T.itemsCount1.s : T.itemsCount.f({'n': isBangla ? _bn('$n') : '$n'});

String _bn(String s) {
  const d = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return s.split('').map((c) => int.tryParse(c) == null ? c : d[int.parse(c)]).join();
}

String tKey(String prefix, String key) {
  for (final v in T.values) {
    if (v.name == '${prefix}_$key') return v.s;
  }
  return key;
}

/// Turn a thrown error into a sentence for a toast.
String errorText(Object e) {
  final raw = e.toString();
  final code = raw.split(':').first;
  for (final v in T.values) {
    if (v.name == 'e_$code') {
      final extra = raw.contains(':') ? raw.substring(raw.indexOf(':') + 1) : '';
      return v.f({'x': extra});
    }
  }
  return raw.replaceFirst('Exception: ', '');
}
